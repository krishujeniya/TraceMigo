"""Offline deterministic vector masters from reviewed geometry and vendored Manrope."""
from pathlib import Path
import json,math
from fontTools.ttLib import TTFont
from fontTools.varLib.instancer import instantiateVariableFont
from fontTools.pens.svgPathPen import SVGPathPen
from fontTools.pens.boundsPen import BoundsPen
from fontTools.pens.transformPen import TransformPen

ROOT=Path(__file__).resolve().parents[2]
SPEC=json.loads((ROOT/'tools/brand/identity.json').read_text())
OUT=ROOT/'apps/web/public/brand'
PALETTE=SPEC['palette']


def halves(color):
 n=SPEC['node']
 left=f'<path d="{SPEC["leftPath"]}"/><circle cx="{n["cx"]}" cy="{n["cy"]}" r="{n["r"]}"/>'
 return f'<g fill="{color}">{left}<g transform="translate(128 0) scale(-1 1)">{left}</g></g>'


def svg(body,width=128,height=128,title='TraceMigo'):
 return f'<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 {width} {height}" width="{width}" height="{height}" role="img" aria-labelledby="title"><title id="title">{title}</title>{body}</svg>\n'


def text_path(text,weight,size,x=0,center_y=None,baseline=None):
 font=instantiateVariableFont(TTFont(OUT/'fonts/manrope-variable.ttf'),{'wght':weight},inplace=False)
 glyphs=font.getGlyphSet();cmap=font.getBestCmap();units=font['head'].unitsPerEm;scale=size/units
 pen=SVGPathPen(glyphs);bounds=BoundsPen(glyphs);advance=0
 # Explicit optical adjustments in em units, applied to both outlined lockups and templates.
 kern={'Tr':-.035,'ra':-.008,'eM':.006,'Mi':-.012,'go':-.008}
 for index,char in enumerate(text):
  if index:advance+=kern.get(text[index-1]+char,0)*units
  glyph=glyphs[cmap[ord(char)]]
  glyph.draw(TransformPen(pen,(1,0,0,1,advance,0)))
  glyph.draw(TransformPen(bounds,(1,0,0,1,advance,0)))
  advance+=font['hmtx'][cmap[ord(char)]][0]
 minx,miny,maxx,maxy=bounds.bounds
 y=baseline if baseline is not None else center_y+(miny+maxy)*scale/2
 body=f'<path transform="translate({x:.4f} {y:.4f}) scale({scale:.6f} {-scale:.6f})" d="{pen.getCommands()}"/>'
 return body,advance*scale


def generate():
 OUT.mkdir(parents=True,exist_ok=True)
 for name in ['teal','ink','mint','white']:
  (OUT/f'mark-{name}.svg').write_text(svg(halves(PALETTE[name])))
 word,width=text_path(SPEC['wordmark'],700,64,x=144,center_y=68)
 lockup_width=math.ceil(144+width+26)
 for name,mark,text in [('primary','teal','ink'),('ink','ink','ink'),('reverse','mint','paper')]:
  (OUT/f'lockup-{name}.svg').write_text(svg(halves(PALETTE[mark])+f'<g fill="{PALETTE[text]}">{word}</g>',lockup_width,128))
 for name,color in [('ink','ink'),('reverse','paper')]:
  word_only,word_width=text_path(SPEC['wordmark'],700,64,x=24,center_y=64)
  (OUT/f'wordmark-{name}.svg').write_text(svg(f'<g fill="{PALETTE[color]}">{word_only}</g>',math.ceil(word_width+48),128))
 for name,bg,fg,scale in [('favicon','ink','mint',1),('app','paper','teal',1),('maskable','ink','mint',SPEC['maskableScale']),('avatar','ink','mint',.9)]:
  offset=128*(1-scale)/2
  body=f'<rect width="128" height="128" fill="{PALETTE[bg]}"/><g transform="translate({offset:.4f} {offset:.4f}) scale({scale})">{halves(PALETTE[fg])}</g>'
  (OUT/f'{name}-master.svg').write_text(svg(body))
 # Social artwork stays a template; it makes no availability, efficacy or employer claim.
 heading,_=text_path('Read code.',700,62,x=80,baseline=318)
 heading2,_=text_path('Think together.',700,62,x=80,baseline=402)
 caption,_=text_path('Understand unfamiliar code, one trace at a time.',400,25,x=80,baseline=486)
 lockup=(OUT/'lockup-primary.svg').read_text().split('</title>',1)[1].rsplit('</svg>',1)[0]
 social=f'<rect width="1200" height="630" fill="{PALETTE["paper"]}"/><g transform="translate(58 48) scale(.72)">{lockup}</g><g fill="{PALETTE["ink"]}">{heading}{heading2}{caption}</g><g transform="translate(880 230) scale(1.7)">{halves(PALETTE["teal"])}</g>'
 (OUT/'social-preview.svg').write_text(svg(social,1200,630,'TraceMigo — Read code. Think together.'))
 # Single source for application primitives and semantic interaction states.
 lines=['/* Generated by tools/brand/generate.py; source: tools/brand/identity.json. */',':root {']
 for name,value in PALETTE.items():lines.append(f'  --brand-{name}: {value};')
 lines+=['  --font-sans: var(--font-manrope, "Manrope"), system-ui, sans-serif;','  --font-code: ui-monospace, "Cascadia Code", "SFMono-Regular", Menlo, Consolas, monospace;','  --weight-body: 400;','  --weight-medium: 500;','  --weight-heading: 700;','  --radius-control: .5rem;','  --radius-panel: .75rem;','  --focus-width: 3px;','  --focus-offset: 3px;']
 for name,value in [('1','.25'),('2','.5'),('3','.75'),('4','1'),('6','1.5'),('8','2'),('12','3')]:lines.append(f'  --space-{name}: {value}rem;')
 lines.append('}')
 for theme in ['light','dark']:
  declarations='\n'.join(f'  --color-{key}: var(--brand-{value});' for key,value in SPEC['themes'][theme].items())
  if theme=='light':lines.extend([':root, [data-theme="light"] {',declarations,'  color-scheme: light;','}'])
  else:
   lines.extend(['[data-theme="dark"] {',declarations,'  color-scheme: dark;','}','@media (prefers-color-scheme: dark) {',':root:not([data-theme="light"]) {',declarations,'  color-scheme: dark;','}','}'])
 (ROOT/'packages/ui/src/tokens.css').write_text('\n'.join(lines)+'\n')
 n=SPEC['node'];path=SPEC['leftPath']
 component=f'''/** Generated identity geometry. Keep both halves equal; edit tools/brand/identity.json. */
export function BrandMark({{ className, label }}: {{ readonly className?: string; readonly label?: string }}) {{
  return <svg viewBox="0 0 128 128" width="128" height="128" className={{className}} role={{label ? "img" : undefined}} aria-label={{label}} aria-hidden={{label ? undefined : true}} fill="currentColor">
    <path d="{path}" /><circle cx="{n['cx']}" cy="{n['cy']}" r="{n['r']}" />
    <g transform="translate(128 0) scale(-1 1)"><path d="{path}" /><circle cx="{n['cx']}" cy="{n['cy']}" r="{n['r']}" /></g>
  </svg>;
}}
export function BrandLockup({{ label = "TraceMigo" }}: {{ readonly label?: string }}) {{
  return <picture className="brand-lockup"><source media="(prefers-color-scheme: dark)" srcSet="/brand/lockup-reverse.svg" /><img src="/brand/lockup-primary.svg" alt={{label}} width="{lockup_width}" height="128" /></picture>;
}}
'''
 (ROOT/'packages/ui/src/brand.tsx').write_text(component)
 metadata={'lockup_width':lockup_width,'lockup_height':128,'font_weight':700,'center_gap_units':16,'visible_bounds':[26,28,102,108],'clear_space_min_units':19,'optical_kerning_em':{'Tr':-.035,'ra':-.008,'eM':.006,'Mi':-.012,'go':-.008}}
 (OUT/'geometry.json').write_text(json.dumps(metadata,indent=2)+'\n')
 print('Generated SVG masters, outlined wordmarks, UI mark/lockup, and light/dark tokens.')

if __name__=='__main__':generate()
